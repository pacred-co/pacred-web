alter table public.momo_invoice_upload
  add column if not exists file_hash text;

comment on column public.momo_invoice_upload.file_hash is
  'sha256 (hex) ของไฟล์ต้นฉบับที่อัพ — ลายนิ้วมือเนื้อไฟล์ ใช้ตัดสินว่า "ไฟล์เดียวกัน" (ไม่ใช่ชื่อไฟล์/ขนาด). null = อัพก่อนมีคอลัมน์นี้ หรือเข้ามาทางวางข้อความ (ไม่มีไฟล์ให้แฮช).';

-- คีย์ค้นของ dedupe: (เลขที่ใบ, แฮช) — ตรงกับ WHERE ที่ฝั่งแอปยิงเป๊ะ.
-- ⚠️ เป็น INDEX ธรรมดา **ไม่ใช่ UNIQUE** โดยตั้งใจ: ถ้าบังคับ unique แล้ววันหนึ่ง MOMO ส่งใบ
--    ที่เนื้อไฟล์เหมือนเดิมเป๊ะแต่เราจำเป็นต้องเก็บ (เช่น กู้ประวัติ/นำเข้าย้อนหลัง) จะเขียนไม่ได้
--    และ INSERT ของประวัติ (best-effort) จะล้มเงียบ. การกันซ้ำอยู่ที่ชั้นแอปซึ่งอธิบายผลให้คนเห็นได้.
create index if not exists momo_invoice_upload_hash_idx
  on public.momo_invoice_upload (invoice_no, file_hash)
  where file_hash is not null;

